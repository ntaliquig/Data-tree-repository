import matplotlib.pyplot as plt
from sklearn.tree import plot_tree
import pandas as pd
import re
import numpy as np

# 1. Calculate Expected Weights (BMI) per Grade Level and Category
temp_df = pd.read_csv('/content/cleaned_learner_masterlist (2).csv')

def parse_bmi(val):
    if pd.isna(val): return np.nan, np.nan
    m_val = re.search(r'([0-9\.]+)', str(val))
    m_cat = re.search(r'\((.*?)\)', str(val))
    return (float(m_val.group(1)) if m_val else np.nan), (m_cat.group(1) if m_cat else 'Unknown')

temp_df[['Numeric BMI', 'BMI Status']] = temp_df['Baseline BMI'].apply(lambda x: pd.Series(parse_bmi(x)))
filtered_temp = temp_df[temp_df['BMI Status'].isin(['Normal', 'Underweight'])]
grouped = filtered_temp.groupby(['Grade Level', 'BMI Status'])['Numeric BMI'].mean().round(2).unstack()

# 2. Setup the visualization figure with two subplots
fig, (ax_tree, ax_table) = plt.subplots(2, 1, figsize=(22, 14), gridspec_kw={'height_ratios': [4, 1]}, dpi=300)

# Get feature and class names
feature_names = numerical_cols + categorical_cols
class_names = [str(c) for c in dt_model.classes_]

# Plot the decision tree on the upper subplot
plot_tree(
    dt_model,
    feature_names=feature_names,
    class_names=class_names,
    filled=True,
    rounded=True,
    max_depth=3,
    fontsize=8,
    ax=ax_tree
)
ax_tree.set_title("Decision Tree Visualization (Truncated to Depth 3)", fontsize=16, pad=10)

# Render the custom Reference Table on the lower subplot
ax_table.axis('off')
table_data = [[grade] + list(row) for grade, row in zip(grouped.index, grouped.values)]
col_labels = ['Grade Level', 'Normal Expected Weight (BMI)', 'Underweight Expected Weight (BMI)']

ref_table = ax_table.table(
    cellText=table_data,
    colLabels=col_labels,
    cellLoc='center',
    loc='center'
)
ref_table.auto_set_font_size(False)
ref_table.set_fontsize(10)
ref_table.scale(1.0, 1.5)
ax_table.set_title("Expected Weight Reference Table (Normal vs Underweight)", fontsize=12, pad=10)

plt.tight_layout()
plt.show()

